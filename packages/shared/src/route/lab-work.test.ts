import { describe, expect, it } from 'vitest';
import { labWorkOf } from './lab-work';

describe('labWorkOf', () => {
  it('явно заданная работа лаборатории важнее названий', () => {
    expect(labWorkOf('Хирургический шаблон', ['Имплантация 36'])).toBe('Хирургический шаблон');
  });

  it('узнаёт работу лаборатории по названиям строк этапа', () => {
    expect(labWorkOf(null, ['Коронка керамическая', 'Лечение кариеса', 'Винир E.max'])).toBe('Коронка керамическая, Винир E.max');
  });

  it('без зуботехнических строк лаборатория не нужна', () => {
    expect(labWorkOf(null, ['Лечение кариеса', 'Профессиональная гигиена'])).toBeNull();
  });

  it('не повторяет одинаковые строки', () => {
    expect(labWorkOf(undefined, ['Коронка цирконий', 'Коронка цирконий'])).toBe('Коронка цирконий');
  });
});
